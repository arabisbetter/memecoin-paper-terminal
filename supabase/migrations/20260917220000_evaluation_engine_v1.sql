  open_value_usd numeric(20,8) not null check (open_value_usd >= 0),
  peak_equity_usd numeric(20,8) not null check (peak_equity_usd >= 0),
  trailing_floor_usd numeric(20,8) not null check (trailing_floor_usd >= 0),
