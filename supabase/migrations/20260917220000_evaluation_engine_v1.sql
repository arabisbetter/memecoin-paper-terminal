-- PAPER evaluation engine v1
-- Product rules locked 2026-09-17:
-- $1,000 start, +$5,000 target ($6,000 pass equity), 10% trailing drawdown,
-- $50 max daily loss (UTC, realized + unrealized), 30-day window,
-- 24h retry cooldown, 25% max position/single trade, 5 max open positions,
-- 1 minimum trade, 1% simulated fee. Real funded activation remains disabled
-- until KYC/compliance are configured and approved.

create table if not exists public.paper_evaluations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  attempt_no integer not null check (attempt_no >= 1),
  status text not null default 'active' check (status in ('active','passed','failed','expired','cancelled')),
  starting_balance_usd numeric(20,8) not null default 1000 check (starting_balance_usd > 0),
  profit_target_usd numeric(20,8) not null default 5000 check (profit_target_usd > 0),
  pass_equity_usd numeric(20,8) not null default 6000 check (pass_equity_usd > 0),
  trailing_drawdown_pct numeric(8,4) not null default 10 check (trailing_drawdown_pct > 0 and trailing_drawdown_pct < 100),
  max_daily_loss_usd numeric(20,8) not null default 50 check (max_daily_loss_usd > 0),
  max_position_pct numeric(8,4) not null default 25 check (max_position_pct > 0 and max_position_pct <= 100),
  max_single_trade_pct numeric(8,4) not null default 25 check (max_single_trade_pct > 0 and max_single_trade_pct <= 100),
  max_open_positions integer not null default 5 check (max_open_positions >= 1),
  min_trades integer not null default 1 check (min_trades >= 1),
  starts_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days'),
  ended_at timestamptz,
  cooldown_until timestamptz,
  peak_equity_usd numeric(20,8) not null default 1000,
  trailing_floor_usd numeric(20,8) not null default 900,
  last_equity_usd numeric(20,8) not null default 1000,
  last_cash_usd numeric(20,8) not null default 1000,
  last_open_value_usd numeric(20,8) not null default 0,
  daily_anchor_date date not null default ((now() at time zone 'utc')::date),
  daily_anchor_equity_usd numeric(20,8) not null default 1000,
  daily_loss_usd numeric(20,8) not null default 0,
  current_drawdown_pct numeric(8,4) not null default 0,
  trades_count integer not null default 0,
  failure_reason text,
  passed_at timestamptz,
  last_mark_at timestamptz,
  last_mark_source text,
  data_status text not null default 'DEGRADED' check (data_status in ('LIVE','DEGRADED','STALE','UNAVAILABLE')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id,attempt_no)
);

create unique index if not exists paper_evaluations_one_active_per_user
  on public.paper_evaluations(user_id) where status='active';
create index if not exists paper_evaluations_user_created_idx
  on public.paper_evaluations(user_id,created_at desc);
create index if not exists paper_evaluations_status_idx
  on public.paper_evaluations(status,expires_at);

