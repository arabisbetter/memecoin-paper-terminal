create or replace function public.paper_start_evaluation_v1()
returns jsonb
language plpgsql
security definer
set search_path=public,auth,pg_temp
as $$
declare
  uid uuid := auth.uid();
  v_is_anonymous boolean;
  v_active public.paper_evaluations%rowtype;
  v_last public.paper_evaluations%rowtype;
  v_attempt integer;
  v_open_count integer;
  v_cash numeric;
  v_eval public.paper_evaluations%rowtype;
  v_missing_legal integer;
begin
  if uid is null then raise exception 'authentication required'; end if;
  select is_anonymous into v_is_anonymous from auth.users where id=uid;
  if coalesce(v_is_anonymous,true) then
    raise exception 'RECOVERABLE_LOGIN_REQUIRED: link a verified email or X identity before entering an evaluation';
  end if;

  select count(*) into v_missing_legal
  from (values ('tos','v2'),('privacy','v1'),('risk_disclosure','v2')) req(document_type,document_version)
  where not exists (
    select 1 from public.legal_acceptances l
    where l.user_id=uid and l.document_type=req.document_type and l.document_version=req.document_version
  );
  if v_missing_legal>0 then raise exception 'LEGAL_ACCEPTANCE_REQUIRED: accept the current PAPER terms and risk disclosure'; end if;

  select * into v_active from public.paper_evaluations
  where user_id=uid and status='active' order by starts_at desc limit 1;
  if v_active.id is not null then return to_jsonb(v_active); end if;

  select * into v_last from public.paper_evaluations
  where user_id=uid order by attempt_no desc limit 1;
  if v_last.status='passed' then raise exception 'evaluation already passed'; end if;
  if v_last.cooldown_until is not null and v_last.cooldown_until>now() then
    raise exception 'EVALUATION_COOLDOWN: next attempt available at %',v_last.cooldown_until;
  end if;

  select count(*) into v_open_count from public.paper_positions
  where user_id=uid and status='open' and coalesce(accounting_version,'')='usd_v2' and quantity_tokens>0;
  if v_open_count>0 then raise exception 'Close all PAPER positions before starting an evaluation'; end if;

  select cash_usd into v_cash from public.paper_accounts where user_id=uid for update;
  if v_cash is null then raise exception 'PAPER account not found'; end if;
  v_attempt:=coalesce(v_last.attempt_no,0)+1;

  insert into public.paper_evaluations(
    user_id,attempt_no,status,starting_balance_usd,profit_target_usd,pass_equity_usd,
    trailing_drawdown_pct,max_daily_loss_usd,max_position_pct,max_single_trade_pct,
    max_open_positions,min_trades,starts_at,expires_at,peak_equity_usd,trailing_floor_usd,
    last_equity_usd,last_cash_usd,last_open_value_usd,daily_anchor_date,daily_anchor_equity_usd,
    daily_loss_usd,current_drawdown_pct,data_status
  ) values(
    uid,v_attempt,'active',1000,5000,6000,10,50,25,25,5,1,now(),now()+interval '30 days',
    1000,900,1000,1000,0,(now() at time zone 'utc')::date,1000,0,0,'DEGRADED'
  ) returning * into v_eval;

  update public.paper_accounts
  set starting_balance_usd=1000,cash_usd=1000,status='active',updated_at=now()
  where user_id=uid;

  insert into public.paper_ledger_entries(
    user_id,account_id,entry_type,amount_usd,balance_after_usd,metadata_json,idempotency_key
  ) values(
    uid,uid,'evaluation_reset',1000-coalesce(v_cash,0),1000,
    jsonb_build_object('evaluation_id',v_eval.id,'attempt_no',v_attempt,'previous_cash_usd',v_cash),
    'evaluation:'||v_eval.id::text||':reset'
  ) on conflict(idempotency_key) do nothing;

  insert into public.paper_evaluation_events(evaluation_id,user_id,event_type,details)
  values(v_eval.id,uid,'evaluation_started',jsonb_build_object('attempt_no',v_attempt,'expires_at',v_eval.expires_at));

  return to_jsonb(v_eval);
end;
$$;
revoke all on function public.paper_start_evaluation_v1() from public,anon;
grant execute on function public.paper_start_evaluation_v1() to authenticated;

create or replace function public.paper_record_evaluation_mark_v1(
  p_user_id uuid,
  p_equity_usd numeric,
  p_cash_usd numeric,
  p_open_value_usd numeric,
  p_source text,
  p_data_status text
) returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  e public.paper_evaluations%rowtype;
  v_now timestamptz:=now();
  v_utc_date date:=(now() at time zone 'utc')::date;
  v_peak numeric;
  v_floor numeric;
  v_anchor numeric;
  v_daily_loss numeric;
  v_drawdown_pct numeric;
  v_trades integer;
  v_status text;
  v_reason text;
  v_app_id uuid;
begin
  if p_user_id is null then raise exception 'user required'; end if;
  if p_equity_usd is null or p_equity_usd<0 or p_cash_usd is null or p_cash_usd<0 or p_open_value_usd is null or p_open_value_usd<0 then
    raise exception 'invalid evaluation mark';
  end if;
  if p_data_status not in ('LIVE','DEGRADED','STALE','UNAVAILABLE') then raise exception 'invalid data status'; end if;

  select * into e from public.paper_evaluations
  where user_id=p_user_id and status='active' order by starts_at desc limit 1 for update;
  if e.id is null then
    return jsonb_build_object('active',false,'status',coalesce((select status from public.paper_evaluations where user_id=p_user_id order by attempt_no desc limit 1),'none'));
  end if;

  select count(*)::int into v_trades from public.paper_trades where evaluation_id=e.id;
  v_peak:=greatest(e.peak_equity_usd,p_equity_usd);
  v_floor:=v_peak*(1-e.trailing_drawdown_pct/100.0);
  v_anchor:=case when e.daily_anchor_date=v_utc_date then e.daily_anchor_equity_usd else p_equity_usd end;
  v_daily_loss:=greatest(v_anchor-p_equity_usd,0);
  v_drawdown_pct:=case when v_peak>0 then greatest((v_peak-p_equity_usd)/v_peak*100,0) else 0 end;
  v_status:='active';

  if v_now>=e.expires_at then
    v_status:='expired'; v_reason:='30_day_window_expired';
  elsif p_equity_usd<=v_floor then
    v_status:='failed'; v_reason:='trailing_drawdown_breach';
  elsif v_daily_loss>=e.max_daily_loss_usd then
    v_status:='failed'; v_reason:='daily_loss_breach';
  elsif p_equity_usd>=e.pass_equity_usd and v_trades>=e.min_trades then
    v_status:='passed';
  end if;

  update public.paper_evaluations set
    status=v_status,
    peak_equity_usd=v_peak,
    trailing_floor_usd=v_floor,
    last_equity_usd=p_equity_usd,
    last_cash_usd=p_cash_usd,
    last_open_value_usd=p_open_value_usd,
    daily_anchor_date=v_utc_date,
    daily_anchor_equity_usd=v_anchor,
    daily_loss_usd=v_daily_loss,
    current_drawdown_pct=v_drawdown_pct,
    trades_count=v_trades,
    failure_reason=v_reason,
    passed_at=case when v_status='passed' then coalesce(passed_at,v_now) else passed_at end,
    ended_at=case when v_status<>'active' then coalesce(ended_at,v_now) else ended_at end,
    cooldown_until=case when v_status in ('failed','expired') then v_now+interval '24 hours' else cooldown_until end,
    last_mark_at=v_now,
    last_mark_source=p_source,
    data_status=p_data_status,
    updated_at=v_now
  where id=e.id;

  insert into public.paper_evaluation_marks(
    evaluation_id,user_id,equity_usd,cash_usd,open_value_usd,peak_equity_usd,trailing_floor_usd,
    daily_loss_usd,current_drawdown_pct,source,data_status,marked_at
  ) values(e.id,p_user_id,p_equity_usd,p_cash_usd,p_open_value_usd,v_peak,v_floor,v_daily_loss,v_drawdown_pct,p_source,p_data_status,v_now);

  if v_status<>'active' and e.status='active' then
    insert into public.paper_evaluation_events(evaluation_id,user_id,event_type,details)
    values(e.id,p_user_id,'evaluation_'||v_status,jsonb_build_object('equity_usd',p_equity_usd,'reason',v_reason,'trades_count',v_trades));
  end if;

  if v_status='passed' then
    insert into public.paper_funded_profiles(user_id,stage,kyc_status,updated_at)
    values(p_user_id,'kyc_required','required',v_now)
    on conflict(user_id) do update set stage='kyc_required',kyc_status='required',updated_at=v_now;

    if not exists(select 1 from public.paper_funded_applications where user_id=p_user_id and status in ('kyc_required','kyc_pending','approved','active')) then
      insert into public.paper_funded_applications(user_id,status,qualification_snapshot,applied_at,updated_at)
      values(p_user_id,'kyc_required',jsonb_build_object(
        'evaluation_id',e.id,'attempt_no',e.attempt_no,'passed_equity_usd',p_equity_usd,
        'peak_equity_usd',v_peak,'trades_count',v_trades,'passed_at',v_now,
        'rules',jsonb_build_object('start',1000,'profit_target',5000,'trailing_drawdown_pct',10,'daily_loss_usd',50,'max_position_pct',25,'max_open_positions',5)
      ),v_now,v_now)
      returning id into v_app_id;
    end if;
  end if;

  return jsonb_build_object(
    'active',v_status='active',
    'id',e.id,
    'attempt_no',e.attempt_no,
    'status',v_status,
    'equity_usd',round(p_equity_usd,8),
    'cash_usd',round(p_cash_usd,8),
    'open_value_usd',round(p_open_value_usd,8),
    'peak_equity_usd',round(v_peak,8),
    'trailing_floor_usd',round(v_floor,8),
    'current_drawdown_pct',round(v_drawdown_pct,4),
    'daily_loss_usd',round(v_daily_loss,8),
    'daily_loss_limit_usd',e.max_daily_loss_usd,
    'trades_count',v_trades,
    'min_trades',e.min_trades,
    'pass_equity_usd',e.pass_equity_usd,
    'profit_target_usd',e.profit_target_usd,
    'starts_at',e.starts_at,
    'expires_at',e.expires_at,
    'cooldown_until',case when v_status in ('failed','expired') then v_now+interval '24 hours' else e.cooldown_until end,
    'failure_reason',v_reason,
    'data_status',p_data_status,
    'source',p_source,
    'funded_activation_enabled',(select real_funded_activation from public.paper_platform_flags where id=true)
  );
end;
$$;
