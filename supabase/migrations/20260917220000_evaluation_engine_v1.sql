create or replace function public.paper_stamp_active_evaluation()
returns trigger
language plpgsql
security definer
set search_path=public,pg_temp
as $$
begin
  if new.evaluation_id is null and new.user_id is not null then
    select e.id into new.evaluation_id
    from public.paper_evaluations e
    where e.user_id=new.user_id and e.status='active'
    order by e.starts_at desc
    limit 1;
  end if;
  return new;
end;
$$;
